"""Generated build artifacts must not be source-tracked.

Source scans should inspect source, not generated bytecode or local engine
build products. This fails if `__pycache__`, `*.pyc`, or built `pactree_engine*.so`
artifacts get committed under `src/` or `tests/`.
"""

import subprocess
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent


def _git_ls_files(*patterns: str) -> list[str]:
    result = subprocess.run(
        ["git", "-C", str(_ROOT), "ls-files", "--", *patterns],
        capture_output=True,
        text=True,
        check=True,
    )
    return [line for line in result.stdout.splitlines() if line]


def test_no_tracked_generated_artifacts():
    tracked = _git_ls_files(
        "src/**/*.pyc",
        "tests/**/*.pyc",
        "src/**/__pycache__/**",
        "tests/**/__pycache__/**",
        "src/pactree/*.so",
        "src/pactree/**/*.so",
    )
    assert not tracked, f"generated artifacts are source-tracked: {tracked}"


def test_gitignore_covers_generated_artifacts():
    gitignore = (_ROOT / ".gitignore").read_text()
    for needle in ("__pycache__", "*.so", "target/", ".venv"):
        assert needle in gitignore, f".gitignore is missing {needle!r}"
